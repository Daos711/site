/* Optional browser acceptance test. Provide PLAYWRIGHT_MODULE and CHROMIUM_PATH
 * when Playwright is not installed in this project. Serve out/ at GOTHIC_TEST_URL. */
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const url = process.env.GOTHIC_TEST_URL || 'http://127.0.0.1:8765/apps/gothic-locks';
const artifacts = process.env.GOTHIC_TEST_OUTPUT || path.resolve('work/gothic-browser');
const results = [];
const record = (name) => { results.push(name); console.log('PASS ' + name); };
const appText = async (page) => page.locator('main').innerText();
const waitText = (page, text) => page.getByText(text, { exact: false }).first().waitFor({ timeout: 30000 });
(async () => {
  await fs.mkdir(artifacts, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, serviceWorkers: 'allow' });
  const errors = [];
  const page = await context.newPage();
  page.on('pageerror', (error) => errors.push(error.message));
  // External analytics and math assets are unrelated to this app; make the test deterministic.
  await context.route(/https:\/\/(cdn\.jsdelivr\.net|www\.googletagmanager\.com)\//, (route) => route.abort());
  try {
    await page.goto(url, { waitUntil: 'networkidle' });
    await waitText(page, 'Доступно офлайн');
    await page.screenshot({ path: path.join(artifacts, 'desktop.png'), fullPage: true });
    assert.equal(await page.getByRole('heading', { name: 'Gothic Remake — Замки' }).count(), 1);
    record('Desktop shell, React hydration and verified complete offline cache');
    await page.setViewportSize({ width: 412, height: 915 });
    await page.getByRole('button', { name: /^Старый лагерь За стенами/ }).click();
    await page.getByRole('button', { name: /^Сундук Скатти/ }).click();
    await waitText(page, 'ШАГ 1 ИЗ');
    assert.match(await appText(page), /№ 5[\s\S]*№ 4[\s\S]*№ 3[\s\S]*№ 2[\s\S]*№ 1/);
    assert.equal(await page.getByRole('button', { name: 'Без навыка', exact: true }).getAttribute('aria-pressed'), 'true');
    await page.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; window.scrollTo({top:0,behavior:'instant'}); });
    await page.screenshot({ path: path.join(artifacts, 'scatty-mobile.png'), fullPage: true });
    record('Old Camp → Scatty → no skill: solution and bottom-first numbering');
    await page.getByRole('button', { name: 'Мастер', exact: true }).click();
    await page.getByRole('button', { name: 'Готово, следующий шаг' }).click();
    await waitText(page, 'ШАГ 2 ИЗ');
    await page.reload({ waitUntil: 'networkidle' });
    await waitText(page, 'ШАГ 2 ИЗ');
    assert.equal(await page.getByRole('button', { name: 'Мастер', exact: true }).getAttribute('aria-pressed'), 'true');
    await page.getByRole('button', { name: 'Обучен', exact: true }).click();
    await waitText(page, 'ШАГ 2 ИЗ');
    record('Skill and progress survive reload; changing skill preserves the instruction');
    await page.getByRole('button', { name: 'Отметить вскрытым', exact: true }).click();
    await page.getByRole('button', { name: 'Положения изменились / отмычка сломалась' }).click();
    await page.getByRole('button', { name: 'Назад', exact: true }).click();
    await waitText(page, 'Состояние этого замка изменено');
    assert.doesNotMatch(await appText(page), /ШАГ \d+ ИЗ/);
    await page.reload({ waitUntil: 'networkidle' });
    await waitText(page, 'Состояние этого замка изменено');
    assert.equal(await page.getByRole('button', { name: 'Уже вскрыт', exact: true }).getAttribute('aria-pressed'), 'true');
    await page.getByRole('button', { name: 'Проверил: исходные позиции и связи совпадают' }).click();
    await waitText(page, 'ШАГ 1 ИЗ');
    record('Changed-state protection persists; old steps cannot silently resume');
    await page.getByText(/Вся комбинация ·/).click();
    await page.getByRole('button', { name: 'Копировать комбинацию' }).click();
    await waitText(page, 'Комбинация скопирована');
    record('Copy complete grouped solution');
    await context.setOffline(true);
    await waitText(page, 'Без интернета');
    await page.reload({ waitUntil: 'networkidle' });
    await waitText(page, 'ШАГ 1 ИЗ');
    assert.equal(await page.evaluate(async () => { try { await fetch('/uncached-offline-proof-' + Date.now()); return false; } catch { return true; } }), true);
    await page.getByRole('button', { name: 'Все замки', exact: true }).click();
    await page.getByRole('textbox', { name: 'Поиск сундука или персонажа' }).fill('рецепт');
    await page.getByRole('button', { name: /Кор Галом/ }).first().click();
    await waitText(page, 'ШАГ 1 ИЗ');
    assert.match(await appText(page), /Кор Галом/);
    record('Offline reload, search and fresh worker calculation for Cor Galom');
    const licenses = await context.newPage();
    await licenses.goto(new URL('/apps/gothic-locks-licenses.txt', url).href);
    assert.match(await licenses.locator('body').innerText(), /Permission is hereby granted/);
    assert.match(await licenses.locator('body').innerText(), /Viktor Murzak/);
    await licenses.close();
    record('Full upstream license notices remain readable offline');
    await page.getByRole('button', { name: 'Все замки', exact: true }).click();
    await page.getByRole('button', { name: 'Моего сундука нет', exact: true }).click();
    await page.getByRole('button', { name: 'Пластина 1, позиция 1', exact: true }).click();
    await page.getByRole('checkbox', { name: /Я сверил/ }).check();
    await page.getByRole('button', { name: 'Рассчитать безопасное решение' }).click();
    await waitText(page, 'ШАГ 1 ИЗ');
    assert.match(await appText(page), /влево\s+3\s+раз/);
    await page.getByRole('button', { name: 'Готово, следующий шаг' }).click();
    await waitText(page, 'Все штифты в центре');
    record('Offline manual editor, physical direction, grouped command and completion');
    await page.getByRole('button', { name: 'К каталогу', exact: true }).click();
    await page.getByRole('button', { name: 'Моего сундука нет', exact: true }).click();
    await page.getByRole('button', { name: 'Пластина 1, позиция 1', exact: true }).click();
    await page.getByRole('button', { name: 'Пластина 2, позиция 7', exact: true }).click();
    await page.getByRole('combobox', { name: 'Связь из пластины 1 в 2' }).selectOption('1');
    await page.getByRole('combobox', { name: 'Связь из пластины 2 в 1' }).selectOption('1');
    await page.getByRole('checkbox', { name: /Я сверил/ }).check();
    await page.getByRole('button', { name: 'Рассчитать безопасное решение' }).click();
    await waitText(page, 'Безопасного решения нет');
    record('Unsolvable manual configuration produces no unsafe instruction');
    await page.getByRole('button', { name: 'К каталогу', exact: true }).click();
    for (const width of [320, 360, 412, 768, 1440]) {
      await page.setViewportSize({ width, height: 915 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'overflow at ' + width);
    }
    await page.setViewportSize({ width: 412, height: 915 });
    await page.getByRole('textbox', { name: 'Поиск сундука или персонажа' }).fill('несуществующий сундук');
    await waitText(page, 'Пока ничего не найдено');
    await page.getByRole('button', { name: 'Сбросить фильтры' }).click();
    await page.getByRole('checkbox', { name: 'Скрыть вскрытые' }).check();
    await page.getByRole('textbox', { name: 'Поиск сундука или персонажа' }).fill('Скатти');
    await waitText(page, 'Пока ничего не найдено');
    await page.getByRole('button', { name: 'Сбросить фильтры' }).click();
    await page.getByRole('checkbox', { name: 'Ценные предметы' }).check();
    assert.ok(await page.getByRole('button', { name: /^Сундук Скатти/ }).count());
    await page.getByRole('checkbox', { name: 'Ценные предметы' }).uncheck();
    await page.screenshot({ path: path.join(artifacts, 'home-mobile.png'), fullPage: true });
    record('Responsive 320–1440 px, search empty state, opened and valuable filters');
    await page.getByRole('button', { name: 'Моего сундука нет', exact: true }).click();
    await page.getByRole('combobox', { name: 'Количество пластин' }).selectOption('7');
    await page.setViewportSize({ width: 320, height: 820 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '7-plate editor body overflows');
    await page.screenshot({ path: path.join(artifacts, 'manual-320.png'), fullPage: true });
    record('Seven-plate editor at 320 px: table scroll contained inside page');
    await context.setOffline(false);
    const corrupted = await browser.newContext({ viewport: { width: 412, height: 915 } });
    await corrupted.addInitScript(() => localStorage.setItem('lab.gothic-locks.v1', '{broken'));
    const other = await corrupted.newPage();
    await other.goto(url, { waitUntil: 'networkidle' });
    await other.getByRole('textbox', { name: 'Поиск сундука или персонажа' }).fill('Скатти');
    await other.getByRole('button', { name: /^Сундук Скатти/ }).click();
    await waitText(other, 'ШАГ 1 ИЗ');
    await corrupted.close();
    record('Corrupted local storage recovers to usable defaults');
    assert.deepEqual(errors, []);
    await fs.writeFile(path.join(artifacts, 'result.json'), JSON.stringify({ passed: results.length, results, errors }, null, 2));
  } finally {
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
