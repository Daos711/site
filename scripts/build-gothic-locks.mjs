import { createHash } from "node:crypto";
import { access, copyFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, extname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import sharp from "sharp";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = join(root, "src", "lib", "gothic-locks");
const publicDirectory = join(root, "public");
const outputDirectory = join(root, "out");
const appPath = "/apps/gothic-locks";
const workerPath = "/apps/gothic-locks-worker.js";
const corePath = "/apps/gothic-locks-core";
const prepareOnly = process.argv.includes("--prepare");
const origin = "https://gothic-locks.invalid";
const textExtensions = new Set([".html", ".txt", ".js", ".css", ".json", ".webmanifest"]);
const assetExtensions = /\.(?:m?js|css|woff2?|ttf|otf|png|svg|jpe?g|webp|avif|ico|json|webmanifest|txt)$/i;
const exists = async (path) => {
  try { await access(path); return true; } catch { return false; }
};
const put = async (path, content) => {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
};
const normalize = (path) => path.split(sep).join("/");
const within = (directory, path) => {
  const difference = relative(directory, path);
  return difference !== ".." && !difference.startsWith(".." + sep) && !isAbsolute(difference);
};

// Compile the worker from the same simulator used by the UI and tests.
async function prepareWorker() {
  const queue = ["solver.ts"];
  const modules = new Set();
  while (queue.length) {
    const filename = queue.shift();
    if (modules.has(filename)) continue;
    modules.add(filename);
    const path = resolve(sourceDirectory, filename);
    if (!within(sourceDirectory, path)) throw new Error("Worker dependency escaped the core directory: " + filename);
    const source = await readFile(path, "utf8");
    const parsed = ts.preProcessFile(source, true, true);
    for (const dependency of parsed.importedFiles) {
      if (!dependency.fileName.startsWith(".")) throw new Error("Worker requires a browser-local import: " + dependency.fileName);
      const dependencyPath = resolve(dirname(path), dependency.fileName.replace(/\.js$/, "") + ".ts");
      if (!within(sourceDirectory, dependencyPath)) throw new Error("Invalid worker dependency");
      queue.push(normalize(relative(sourceDirectory, dependencyPath)));
    }
    const compiled = ts.transpileModule(source, {
      fileName: filename,
      reportDiagnostics: true,
      compilerOptions: {
        target: ts.ScriptTarget.ES2020,
        module: ts.ModuleKind.ES2020,
        importsNotUsedAsValues: ts.ImportsNotUsedAsValues.Remove,
        sourceMap: false,
      },
    });
    const errors = compiled.diagnostics?.filter((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error) ?? [];
    if (errors.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(errors, {
      getCanonicalFileName: (name) => name,
      getCurrentDirectory: () => root,
      getNewLine: () => "\n",
    }));
    const javascript = compiled.outputText.replace(
      /((?:from\s*|import\s*)["'])(\.{1,2}\/[^"']+)(["'])/g,
      (whole, prefix, specifier, suffix) => prefix + (extname(specifier) ? specifier : specifier + ".js") + suffix,
    );
    await put(join(publicDirectory, corePath, filename.replace(/\.ts$/, ".js")), "// Generated from src/lib/gothic-locks/" + filename + "; do not edit.\n" + javascript);
  }
  const worker = [
    "// Generated by scripts/build-gothic-locks.mjs; do not edit.",
    'import { solveLock } from "./gothic-locks-core/solver.js";',
    "self.onmessage = (event) => {",
    "  const data = event.data ?? {};",
    "  try {",
    "    const result = solveLock(data.config, data.limits);",
    "    self.postMessage({ id: data.id, result });",
    "  } catch (error) {",
    '    self.postMessage({ id: data.id, error: error instanceof Error ? error.message : "Не удалось рассчитать замок." });',
    "  }",
    "};",
    "",
  ].join("\n");
  await put(join(publicDirectory, workerPath), worker);
  return [...modules].map((name) => corePath + "/" + name.replace(/\.ts$/, ".js")).concat(workerPath);
}

async function prepareLicenses() {
  const murzav = await readFile(join(sourceDirectory, "vendor", "Murzav-LICENSE.txt"), "utf8");
  const arminek = await readFile(join(sourceDirectory, "vendor", "Arminek-NOTICE.txt"), "utf8");
  const path = appPath + "-licenses.txt";
  const notices = "Third-party notices / Gothic Remake — Замки\n\n" +
    "gothic-lockpick-solver — https://github.com/Murzav/gothic-lockpick-solver\n\n" +
    murzav.trimEnd() + "\n\n" + "=".repeat(72) + "\n\n" + arminek.trimEnd() + "\n";
  await put(join(publicDirectory, path), notices);
  return path;
}

async function prepareIcons() {
  const source = await readFile(join(publicDirectory, "apps", "gothic-locks-icons", "icon.svg"));
  const paths = [];
  for (const size of [192, 512]) {
    const path = "/apps/gothic-locks-icons/icon-" + size + ".png";
    await sharp(source).resize(size, size).png({ compressionLevel: 9 }).toFile(join(publicDirectory, path));
    paths.push(path);
  }
  return paths;
}

function resourceReferences(content, basePath) {
  const references = new Set();
  const add = (reference) => {
    const cleaned = reference.replace(/\\\//g, "/").replace(/&amp;/g, "&");
    if (!cleaned || /^(?:data|blob|javascript|mailto|tel):/i.test(cleaned) || cleaned.startsWith("#")) return;
    try {
      const url = new URL(cleaned, origin + basePath);
      // The worker template is replaced after hashing. Including it would create a circular version.
      if (url.pathname === appPath + "-sw.js" || url.pathname === appPath + "-precache.json") return;
      // Router implementation strings are not dependencies of this app document.
      if (url.pathname.endsWith(".txt") && ![appPath + ".txt", appPath + "-licenses.txt"].includes(url.pathname)) return;
      if (url.origin === origin && assetExtensions.test(url.pathname)) references.add(url.pathname);
    } catch { /* Ignore non-URL strings in compiled modules. */ }
  };
  for (const match of content.matchAll(/(?:src|href)\s*=\s*["']([^"']+)["']/g)) add(match[1]);
  for (const match of content.matchAll(/url\(\s*["']?([^"')\s]+)["']?\s*\)/g)) add(match[1]);
  for (const match of content.matchAll(/["'\`](\.{1,2}\/[^"'\`\s]+|\/[^"'\`\s]+)["'\`]/g)) add(match[1]);
  // Flight escapes quotes; Turbopack can refer to static/chunks directly.
  for (const match of content.matchAll(/\/_next\/static\/[a-zA-Z0-9_.~%/+@-]+/g)) add(match[0]);
  for (const match of content.matchAll(/["'\`](?:\/?_next\/)?(static\/(?:chunks|media)\/[^"'\`\s]+)["'\`]/g)) add("/_next/" + match[1]);
  return references;
}

async function collectPrecache(initialPaths) {
  const pending = [...initialPaths];
  const found = new Set();
  while (pending.length) {
    const resourcePath = pending.shift();
    if (found.has(resourcePath)) continue;
    const filePath = resolve(outputDirectory, "." + decodeURIComponent(resourcePath));
    if (!within(outputDirectory, filePath)) throw new Error("Resource is outside export directory: " + resourcePath);
    if (!(await exists(filePath))) throw new Error("Offline resource is missing: " + resourcePath);
    if (!(await stat(filePath)).isFile()) continue;
    found.add(resourcePath);
    if (textExtensions.has(extname(filePath))) {
      const content = await readFile(filePath, "utf8");
      for (const reference of resourceReferences(content, resourcePath)) {
        // JS can contain optional URLs; concrete HTML/CSS asset references are required.
        const referencedFile = resolve(outputDirectory, "." + decodeURIComponent(reference));
        if (within(outputDirectory, referencedFile) && await exists(referencedFile)) pending.push(reference);
        else if ([".html", ".css", ".webmanifest"].includes(extname(filePath)) && !reference.includes("\${")) {
          throw new Error("A linked offline asset was not exported: " + reference + " in " + resourcePath);
        }
      }
    }
  }
  return [...found].sort();
}

async function main() {
  const workerPaths = await prepareWorker();
  const generatedPaths = [...workerPaths, ...await prepareIcons(), await prepareLicenses()];
  if (prepareOnly) {
    console.log("Gothic Locks: prepared worker, " + (workerPaths.length - 1) + " core modules, 192/512 icons and full third-party notices.");
    return;
  }
  const shell = appPath + ".html";
  if (!(await exists(join(outputDirectory, shell)))) {
    throw new Error("Run next build first: out/apps/gothic-locks.html was not found. For development, pass --prepare.");
  }
  const staticPaths = [...generatedPaths, appPath + ".webmanifest", "/apps/gothic-locks-icons/icon.svg"];
  for (const path of staticPaths) {
    await mkdir(dirname(join(outputDirectory, path)), { recursive: true });
    await copyFile(join(publicDirectory, path), join(outputDirectory, path));
  }
  // A directory index supports static servers without clean-URL rewrites.
  await mkdir(join(outputDirectory, "apps", "gothic-locks"), { recursive: true });
  await copyFile(join(outputDirectory, shell), join(outputDirectory, "apps", "gothic-locks", "index.html"));
  const initialPaths = [shell, ...staticPaths];
  if (await exists(join(outputDirectory, appPath + ".txt"))) initialPaths.push(appPath + ".txt");
  const precache = await collectPrecache(initialPaths);
  const hash = createHash("sha256");
  let bytes = 0;
  for (const path of precache) {
    const content = await readFile(join(outputDirectory, path));
    hash.update(path).update(content);
    bytes += content.length;
  }
  const template = await readFile(join(publicDirectory, "apps", "gothic-locks-sw.js"), "utf8");
  hash.update(template);
  const version = hash.digest("hex").slice(0, 16);
  const serviceWorker = template.replace("__GOTHIC_CACHE_VERSION__", version).replace("/* GOTHIC_PRECACHE */ []", JSON.stringify(precache, null, 2));
  if (serviceWorker === template || serviceWorker.includes("__GOTHIC_CACHE_VERSION__")) throw new Error("Invalid Gothic Locks service worker template");
  await put(join(outputDirectory, "apps", "gothic-locks-sw.js"), serviceWorker);
  await put(join(outputDirectory, "apps", "gothic-locks-precache.json"), JSON.stringify({
    version, scope: appPath, shell, files: precache.length, bytes, urls: precache,
  }, null, 2) + "\n");
  console.log("Gothic Locks: offline version " + version + ", " + precache.length + " resources, " + (bytes / 1024 / 1024).toFixed(2) + " MiB.");
}
main().catch((error) => {
  console.error("Gothic Locks build failed:", error.message);
  process.exitCode = 1;
});
